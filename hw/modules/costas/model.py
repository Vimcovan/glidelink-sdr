"""Costas loop (QPSK): reference model of glidelink_costas.v at register level.

As GNU Radio's costas_loop_cc of order 4, in fixed point, one sample at a time (phase,
frequency: 2^32 per cycle; samples Q15):

    k  = phase >> 20, C, S = round(32767 cos / sin(2 pi k / 4096))
    y  = x exp(-j phase): yI = sat16((xI C + xQ S + 2^14) >> 15), yQ = sat16((xQ C - xI S + 2^14) >> 15)
    e  = sign(yI) yQ - sign(yQ) yI  (sign(0) = -1), within +-32768
    f' = f + ((e BETA) >> 16),  phase += f' + ((e ALPHA) >> 16),  f = f' within +-FREQ_MAX

which is GNU Radio's freq += beta err; phase += freq + alpha err (err = e / 32768) when
ALPHA = alpha 2^33 / (2 pi) and BETA = beta 2^33 / (2 pi). Disabled: samples pass unchanged.
loop_gains(w): GNU Radio's control loop gains (damping sqrt(2) / 2) as ALPHA, BETA.
"""
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from sc16 import pack, unpack  # noqa: E402
import module_desc  # noqa: E402

M32 = 0xFFFFFFFF


def table():
    k = np.arange(4096)
    return (np.round(32767 * np.cos(2 * np.pi * k / 4096)).astype(np.int64).tolist(),
            np.round(32767 * np.sin(2 * np.pi * k / 4096)).astype(np.int64).tolist())


def loop_gains(w):
    z = math.sqrt(2) / 2
    d = 1 + 2 * z * w + w * w
    alpha, beta = 4 * z * w / d, 4 * w * w / d
    k = 2 ** 33 / (2 * math.pi)
    return round(alpha * k), round(beta * k)


def s32(v):
    v &= M32
    return v - (1 << 32) if v & 0x80000000 else v


def sat16(v):
    return -32768 if v < -32768 else 32767 if v > 32767 else v


class Model(module_desc.RegisterModel):
    def __init__(self, params=None):
        super().__init__(module_desc.load("costas", os.path.dirname(HERE)), params)
        self.tab = table()
        self.phase = 0
        self.f = 0

    def on_write(self, name, value):
        if name == "FREQ":
            self.f = s32(value)
        elif name == "CONTROL" and value & 2:
            self.phase, self.f = 0, s32(self.regs["FREQ"])

    def on_read(self, name):
        if name == "STATUS":
            return self.field("CONTROL", "enable")
        if name == "FREQ":
            return self.f & M32
        if name == "PHASE":
            return self.phase
        return None

    def process(self, words):
        words = np.asarray(words, np.uint32)
        if not self.field("CONTROL", "enable"):
            return words.copy()
        C, S = self.tab
        alpha, beta, fmax = self.regs["ALPHA"], self.regs["BETA"], self.regs["FREQ_MAX"]
        phase, f = self.phase, self.f
        xi, xq = unpack(words)
        oi = np.empty(len(words), np.int64)
        oq = np.empty(len(words), np.int64)
        for n, (a, b) in enumerate(zip(xi.tolist(), xq.tolist())):
            k = phase >> 20
            yi = sat16((a * C[k] + b * S[k] + (1 << 14)) >> 15)
            yq = sat16((b * C[k] - a * S[k] + (1 << 14)) >> 15)
            e = (yq if yi > 0 else -yq) - (yi if yq > 0 else -yi)
            e = -32768 if e < -32768 else 32768 if e > 32768 else e
            f2 = f + ((e * beta) >> 16)
            phase = (phase + f2 + ((e * alpha) >> 16)) & M32
            f = -fmax if f2 < -fmax else fmax if f2 > fmax else f2
            oi[n], oq[n] = yi, yq
        self.phase, self.f = phase, f
        return pack(oi, oq)


def write_rom(path):
    c, s = table()
    lines = ["// generated by hw/modules/costas/model.py (python model.py rom): do not edit",
             "// 4096-point table, {sin, cos}, each round(32767 * f(2 pi k / 4096)); one-cycle read", "",
             "`timescale 1ns/100ps", "", "module glidelink_costas_rom (", "  input             clk,",
             "  input     [11:0]  addr,", "  output reg [31:0] data", ");", "", "  always @(posedge clk)",
             "    case (addr)"]
    for k in range(4096):
        lines.append(f"      12'd{k}: data <= 32'h{(s[k] & 0xFFFF):04X}{(c[k] & 0xFFFF):04X};")
    lines += ["    endcase", "", "endmodule", ""]
    open(path, "w", newline="\n").write("\n".join(lines))


if __name__ == "__main__":
    if (sys.argv[1] if len(sys.argv) > 1 else "") == "rom":
        write_rom(os.path.join(HERE, "glidelink_costas_rom.v"))
    else:
        print(__doc__)
