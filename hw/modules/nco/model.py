"""NCO mixer (frequency shift): bit-exact reference model of glidelink_nco.v.

Each sample x[n] = I + jQ (sc16, word {Q[31:16], I[15:0]}) is multiplied by
exp(j * 2 pi * phase[n] / 2^32), phase[n] = (PHASE + n * FREQ) mod 2^32, where n
counts the samples taken since PHASE was last written (or since reset):

    k     = phase[n] >> 20                       (4096-point table)
    C, S  = round(32767 cos(2 pi k / 4096)), round(32767 sin(2 pi k / 4096))
    re    = sat16((I C - Q S + 2^14) >> 15)
    im    = sat16((I S + Q C + 2^14) >> 15)

so FREQ = f / fs * 2^32 moves the signal up by f. With CONTROL.enable = 0 the
samples pass unchanged and the phase holds. Model: the module at register level (the
software GNU Radio block and the generic test drive it as they drive the PL module).

    python model.py rom       writes glidelink_nco_rom.v (the table)
    python model.py vectors   writes tb/ vectors for the module testbench
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from sc16 import pack, unpack, sat16  # noqa: E402
import module_desc  # noqa: E402

TABLE_BITS = 12


def table():
    k = np.arange(1 << TABLE_BITS)
    c = np.round(32767 * np.cos(2 * np.pi * k / (1 << TABLE_BITS))).astype(np.int64)
    s = np.round(32767 * np.sin(2 * np.pi * k / (1 << TABLE_BITS))).astype(np.int64)
    return c, s


def process(words, freq, phase=0, enable=True):
    """words: uint32 samples; returns (output words, phase after the last sample)"""
    words = np.asarray(words, np.uint32)
    n = len(words)
    if not enable:
        return words.copy(), phase
    ph = (phase + np.arange(n, dtype=np.uint64) * np.uint64(freq)) & np.uint64(0xFFFFFFFF)
    k = (ph >> np.uint64(32 - TABLE_BITS)).astype(np.int64)
    c, s = table()
    C, S = c[k], s[k]
    i, q = unpack(words)
    re = sat16((i * C - q * S + (1 << 14)) >> 15)
    im = sat16((i * S + q * C + (1 << 14)) >> 15)
    return pack(re, im), int((phase + n * freq) & 0xFFFFFFFF)


class Model(module_desc.RegisterModel):
    """glidelink_nco at register level"""

    def __init__(self, params=None):
        super().__init__(module_desc.load("nco", os.path.dirname(HERE)), params)
        self.phase = 0

    def on_write(self, name, value):
        if name == "PHASE" or (name == "CONTROL" and value & 2):     # soft reset: phase = PHASE
            self.phase = self.regs["PHASE"]

    def on_read(self, name):
        if name == "STATUS":
            return self.field("CONTROL", "enable")
        return self.phase if name == "PHASE" else None

    def process(self, words):
        out, self.phase = process(words, self.regs["FREQ"], self.phase, bool(self.field("CONTROL", "enable")))
        return out


def write_rom(path):
    c, s = table()
    lines = [
        "// generated by hw/modules/nco/model.py (python model.py rom): do not edit",
        "// 4096-point table, {sin, cos}, each round(32767 * f(2 pi k / 4096)); one-cycle read",
        "",
        "`timescale 1ns/100ps",
        "",
        "module glidelink_nco_rom (",
        "  input             clk,",
        "  input             ce,",
        "  input     [11:0]  addr,",
        "  output reg [31:0] data",
        ");",
        "",
        "  always @(posedge clk)",
        "    if (ce)",
        "      case (addr)",
    ]
    for k in range(len(c)):
        lines.append(f"        12'd{k}: data <= 32'h{(int(s[k]) & 0xFFFF):04X}{(int(c[k]) & 0xFFFF):04X};")
    lines += ["      endcase", "", "endmodule", ""]
    open(path, "w", newline="\n").write("\n".join(lines))


def write_vectors(d, seed=1, freq=0x0D1B_71E5, phase=0x4000_0000, enable=True):
    """regs.hex: register writes (addr data); in.hex / out.hex: word and tlast per beat"""
    rng = np.random.default_rng(seed)
    os.makedirs(d, exist_ok=True)
    n = 6000
    t = np.arange(n)
    # a tone plus noise near full scale, with some samples at the extremes for saturation
    x = 30000 * np.exp(2j * np.pi * 0.013 * t) + rng.normal(0, 1500, n) + 1j * rng.normal(0, 1500, n)
    i = np.clip(np.round(x.real), -32768, 32767).astype(np.int64)
    q = np.clip(np.round(x.imag), -32768, 32767).astype(np.int64)
    i[::97], q[::97] = -32768, -32768
    i[50::131], q[50::131] = 32767, -32768
    words = pack(i, q)
    out, _ = process(words, freq, phase, enable)
    last = np.zeros(n, int)
    pos = 0
    while pos < n:                          # packets of random length
        pos += int(rng.integers(1, 700))
        last[min(pos, n) - 1] = 1
    regs = [(0x010, freq), (0x014, phase), (0x008, int(enable))]
    open(os.path.join(d, "regs.hex"), "w", newline="\n").write("".join(f"{a:03X} {v:08X}\n" for a, v in regs))
    for name, w in (("in.hex", words), ("out.hex", out)):
        open(os.path.join(d, name), "w", newline="\n").write(
            "".join(f"{int(v):08X} {l}\n" for v, l in zip(w, last)))


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else ""
    if what == "rom":
        write_rom(os.path.join(HERE, "glidelink_nco_rom.v"))
    elif what == "vectors":
        write_vectors(os.path.join(HERE, "tb", "vectors"))                       # about +0.0512 fs
        write_vectors(os.path.join(HERE, "tb", "vectors_neg"), 3, 0xF000_0001, 0)  # about -0.0625 fs
        write_vectors(os.path.join(HERE, "tb", "vectors_bypass"), 4, enable=False)
    else:
        print(__doc__)
