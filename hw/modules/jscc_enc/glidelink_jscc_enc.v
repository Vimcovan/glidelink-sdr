// ***************************************************************************
// GlideLink user module: DeepJSCC-Q encoder (from the competition design,
// docs/phase4_plan.md; description: module.yaml).
//
// Input: one 256x256 RGB image per frame, uint8 in NHWC order (R, G, B of
// pixel 0, then pixel 1, ...), four bytes per 32-bit word, byte 0 in bits
// [7:0] (the order of a numpy uint8 array): 49,152 words per image. Packets
// and tlast are ignored; the encoder counts its own frame.
// Output: 32,768 64-QAM symbols per image, {Q[31:16], I[15:0]} with each half
// the 12-bit Q10 level sign-extended (the OFDM transmitter's input), tlast on
// the last symbol of the image.
//
// The network (competition RTL generated by gen_rtl_top.py, unchanged) runs at
// 250 MHz: the image puts the module on the 250 MHz slot clock.
//
// Registers (4 KB window):
//   0x000  ID          RO  0x4A454E43 ("JENC")
//   0x004  VERSION     RO  {major[15:0], minor[7:0], patch[7:0]}
//   0x008  CONTROL     RW  bit 0: enable (default 1; 0 holds the input off),
//                          bit 1: soft reset (self-clearing)
//   0x00C  STATUS      RO  bit 0: enabled
//   0x010  FRAMES_OUT  RO  images encoded (output frames)
//   0x014  BYTES_IN    RO  input bytes taken (196,608 per image)
// ***************************************************************************

`timescale 1ns/100ps

module glidelink_jscc_enc (
  input             clk,                    // 250 MHz slot
  input             rstn,
  input             flush,

  input             s_axil_awvalid,
  output            s_axil_awready,
  input     [11:0]  s_axil_awaddr,
  input             s_axil_wvalid,
  output            s_axil_wready,
  input     [31:0]  s_axil_wdata,
  output            s_axil_bvalid,
  input             s_axil_bready,
  input             s_axil_arvalid,
  output            s_axil_arready,
  input     [11:0]  s_axil_araddr,
  output            s_axil_rvalid,
  input             s_axil_rready,
  output    [31:0]  s_axil_rdata,

  input             s_axis_tvalid,
  output            s_axis_tready,
  input     [31:0]  s_axis_tdata,
  input     [71:0]  s_axis_tuser,
  input             s_axis_tlast,

  output            m_axis_tvalid,
  input             m_axis_tready,
  output    [31:0]  m_axis_tdata,
  output    [71:0]  m_axis_tuser,
  output            m_axis_tlast
);

  localparam [31:0] ID = 32'h4A454E43;
  localparam [31:0] VERSION = 32'h00010000;

  // ---------------------------------------------------------------------------
  // registers

  wire        wr_en;
  wire [11:0] wr_addr, rd_addr;
  wire [31:0] wr_data;
  reg  [31:0] rd_data;
  reg         enable = 1'b1, soft_rst = 1'b0;
  reg  [31:0] frames_out = 32'd0, bytes_in = 32'd0;

  glidelink_module_axil i_axil (
    .clk(clk), .rstn(rstn),
    .s_axil_awvalid(s_axil_awvalid), .s_axil_awready(s_axil_awready), .s_axil_awaddr(s_axil_awaddr),
    .s_axil_wvalid(s_axil_wvalid), .s_axil_wready(s_axil_wready), .s_axil_wdata(s_axil_wdata),
    .s_axil_bvalid(s_axil_bvalid), .s_axil_bready(s_axil_bready),
    .s_axil_arvalid(s_axil_arvalid), .s_axil_arready(s_axil_arready), .s_axil_araddr(s_axil_araddr),
    .s_axil_rvalid(s_axil_rvalid), .s_axil_rready(s_axil_rready), .s_axil_rdata(s_axil_rdata),
    .wr_en(wr_en), .wr_addr(wr_addr), .wr_data(wr_data), .rd_addr(rd_addr), .rd_data(rd_data));

  always @(posedge clk) begin
    soft_rst <= 1'b0;
    if (!rstn) begin
      enable <= 1'b1;
    end else if (wr_en && wr_addr[11:2] == 10'h002) begin
      enable <= wr_data[0];
      soft_rst <= wr_data[1];
    end
  end

  always @(*) begin
    case (rd_addr[11:2])
      10'h000: rd_data = ID;
      10'h001: rd_data = VERSION;
      10'h002: rd_data = {31'd0, enable};
      10'h003: rd_data = {31'd0, enable};
      10'h004: rd_data = frames_out;
      10'h005: rd_data = bytes_in;
      default: rd_data = 32'd0;
    endcase
  end

  reg  [2:0]  rst_pipe = 3'b000;            // the competition RTL resets asynchronously, active low
  always @(posedge clk) rst_pipe <= {rst_pipe[1:0], rstn && !flush && !soft_rst};
  wire        rst_n = rst_pipe[2];

  // ---------------------------------------------------------------------------
  // words -> bytes -> encoder (competition RTL)

  wire [7:0]  b_tdata;
  wire        b_tvalid, b_tready, w_tready;

  assign s_axis_tready = enable && w_tready;

  axis_unpack8 u_unpack (
    .clk(clk), .rst_n(rst_n),
    .s_tdata(s_axis_tdata), .s_tvalid(s_axis_tvalid && enable), .s_tready(w_tready),
    .m_tdata(b_tdata), .m_tvalid(b_tvalid), .m_tready(b_tready));

  wire [23:0] e_tdata;
  wire        e_tlast;

  blk_enc_0_latent_idx u_encoder (
    .clk(clk), .rst_n(rst_n),
    .s_in_tdata({4'b0, b_tdata}),           // uint8 pixel -> int12 activation (input scale 1/255)
    .s_in_tvalid(b_tvalid), .s_in_tready(b_tready), .s_in_tlast(1'b0), .s_in_tuser(1'b0),
    .m_out_tdata(e_tdata), .m_out_tvalid(m_axis_tvalid), .m_out_tready(m_axis_tready),
    .m_out_tlast(e_tlast), .m_out_tuser());

  assign m_axis_tdata = {{4{e_tdata[23]}}, e_tdata[23:12], {4{e_tdata[11]}}, e_tdata[11:0]};
  assign m_axis_tlast = e_tlast;
  assign m_axis_tuser = 72'd0;

  always @(posedge clk) begin
    if (!rst_n) begin
      frames_out <= 32'd0;
      bytes_in <= 32'd0;
    end else begin
      if (m_axis_tvalid && m_axis_tready && m_axis_tlast)
        frames_out <= frames_out + 32'd1;
      if (b_tvalid && b_tready)
        bytes_in <= bytes_in + 32'd1;
    end
  end

endmodule
